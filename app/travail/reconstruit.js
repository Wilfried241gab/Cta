const fs=require('fs'),crypto=require('crypto');
const oldPath='cta/assets/app-7cdb3cb089.js';
const src=fs.readFileSync(oldPath,'utf8');
const lines=src.split('\n');
const i=lines.findIndex(l=>l.trim().startsWith('const M={'));
const M=new Function('return '+lines[i].replace(/^const M=/,'').replace(/;\s*$/,''))();
const avant={};
for(const [k,v] of Object.entries(M)) avant[k]=Buffer.from(v,'base64').length;
M.rh=fs.readFileSync('travail/rh.html').toString('base64');
lines[i]='const M='+JSON.stringify(M)+';';
let out=lines.join('\n');
const oldHelp="RH:[['Factures CNAMGS','Une facture comporte 10 lignes au plus. Validez-la pour la classer, puis constituez le récapitulatif par fonds et par nature.']";
const newHelp="RH:[['Factures CNAMGS','Une facture comporte 10 lignes au plus. Validez-la pour la classer, puis constituez le récapitulatif par fonds et par nature. Une facture validée reste modifiable ou supprimable (motif obligatoire) tant que l’année n’est pas clôturée.']";
if(!out.includes(oldHelp))throw new Error('texte aide introuvable');
out=out.replace(oldHelp,newHelp);
const hash=crypto.createHash('sha256').update(out).digest('hex').slice(0,10);
const newName=`app-${hash}.js`;
fs.writeFileSync('cta/assets/'+newName,out);
console.log('nouveau fichier',newName,'taille',out.length,'avant rh',avant.rh,'apres rh',Buffer.from(M.rh,'base64').length);
let html=fs.readFileSync('cta/app.html','utf8');
const n=(html.match(/app-7cdb3cb089\.js/g)||[]).length;
html=html.replace(/app-7cdb3cb089\.js/g,newName);
fs.writeFileSync('cta/app.html',html);
console.log('references mises a jour:',n);
fs.writeFileSync('travail/nouveau.txt',newName);
